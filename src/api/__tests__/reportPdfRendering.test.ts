  it("ESR-1: an improved posture reads 'increased by N points' with no malformed glyphs", async () => {
    const buf = await renderToBuffer((out) => generateExecutivePDF(makeExecReport(), out));
    const parsed = await parsePdf(buf);

    // 62 vs 48 (health-style, higher = better) → +14.
    expect(parsed.fullText).toContain("increased by 14 points");
    expect(parsed.fullText).toContain("higher = better");
    // The old malformed label and its raw glyphs must be gone.
    expect(parsed.fullText).not.toContain("unchanged points");
    for (const glyph of ["▲", "▼", "◆", "�", "Æ"]) {
      expect(parsed.fullText.includes(glyph), `PDF text contains malformed char ${JSON.stringify(glyph)}`).toBe(false);
    }
  });

  it("ESR-1: a declined posture reads 'decreased by N points'", async () => {
    const declined = makeExecReport();
    declined.posture = { overall_score: 40, overall_severity: "High", snapshot_date: "2026-07-15" };
    declined.posture_prior = { overall_score: 55, overall_severity: "Moderate", snapshot_date: "2026-04-15" };
    const buf = await renderToBuffer((out) => generateExecutivePDF(declined, out));
    const parsed = await parsePdf(buf);

    expect(parsed.fullText).toContain("decreased by 15 points");
    expect(parsed.fullText).not.toContain("-15 points");
  });

  it("ESR-1: an unchanged posture reads 'no change' (never a malformed percentage)", async () => {
    const flat = makeExecReport();
    flat.posture = { overall_score: 50, overall_severity: "Moderate", snapshot_date: "2026-07-15" };
    flat.posture_prior = { overall_score: 50, overall_severity: "Moderate", snapshot_date: "2026-04-15" };
    const buf = await renderToBuffer((out) => generateExecutivePDF(flat, out));
    const parsed = await parsePdf(buf);

    expect(parsed.fullText).toContain("no change");
    expect(parsed.fullText).not.toMatch(/%[^\s]/); // no stray "%X" style artifacts
    for (const glyph of ["▲", "▼", "◆", "�"]) {
      expect(parsed.fullText.includes(glyph)).toBe(false);
    }
  });

  // ── ESR-2: reconciled domain breakdown renders and sums to the total ────────
  it("ESR-2: domain breakdown shows each domain and its counts sum to Total Active Findings", async () => {
    const buf = await renderToBuffer((out) => generateExecutivePDF(makeExecReport(), out));
    const parsed = await parsePdf(buf);

    expect(parsed.fullText).toContain("Posture Domain Breakdown");
    for (const domain of ["Access Control", "Data Protection", "Vendor Risk"]) {
      expect(parsed.fullText).toContain(domain);
    }
    // Health-style values (higher = better) match what /posture would show.
    expect(parsed.fullText).toContain("40/100");
    expect(parsed.fullText).toContain("8/100");
    expect(parsed.fullText).toContain("72/100");
    // Reconciliation: 2 + 23 + 1 = 26 Total Active Findings.
    expect(parsed.fullText).toContain("TOTAL ACTIVE FINDINGS");
    const fixture = makeExecReport();
    const sum = fixture.posture_domains.reduce((s, d) => s + d.finding_count, 0);
    expect(sum).toBe(26);
    expect(sum).toBe(fixture.posture_finding_total);
  });

  it("ESR-2: with no snapshot, the domain section degrades to a clear message (no crash)", async () => {
    const empty = makeExecReport();
    empty.posture = null;
    empty.posture_prior = null;
    empty.posture_domains = [];
    empty.posture_finding_total = null;
    const buf = await renderToBuffer((out) => generateExecutivePDF(empty, out));
    const parsed = await parsePdf(buf);

    expect(parsed.pages[0]!.text.length).toBeGreaterThan(0);
    expect(parsed.fullText).toContain("Posture Domain Breakdown");
    expect(parsed.fullText).toContain("No posture snapshot exists yet");
    expectNoArtifactPages(parsed);
    expectConsistentPageNumbers(parsed);
    expectNoOverlappingText(await extractBoxes(buf));
  });
