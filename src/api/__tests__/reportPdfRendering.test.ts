// ─── Render + parse helpers ────────────────────────────────────────────────────

async function renderToBuffer(
  generate: (out: NodeJS.WritableStream) => void
): Promise<Buffer> {
  const out = new PassThrough();
  const chunks: Buffer[] = [];
  out.on("data", (c) => chunks.push(c as Buffer));
  const done = new Promise<void>((resolve, reject) => {
    out.on("end", resolve);
    out.on("error", reject);
  });
  generate(out);
  await done;
  return Buffer.concat(chunks);
}

type ParsedPdf = {
  total: number;
  pages: Array<{ num: number; text: string }>;
  fullText: string;
};

async function parsePdf(buf: Buffer): Promise<ParsedPdf> {
  // pdf-parse v2 throws on `instanceof Buffer`, and pdf.js detaches the
  // ArrayBuffer it is given — hand it a copied plain Uint8Array so `buf`
  // stays readable after parsing.
  const parser = new PDFParse(new Uint8Array(buf));
  const result = await parser.getText();
  return { total: result.total, pages: result.pages, fullText: result.text };
}

type TextBox = {
  page: number;
  text: string;
  x0: number; x1: number;
  y0: number; y1: number;
};

/**
 * Every rendered glyph run with its box, in PDF user space (y grows upward).
 * pdf-parse only exposes text, so go to pdfjs directly for the geometry.
 */
async function extractBoxes(buf: Buffer): Promise<TextBox[]> {
  const pdfjs: any = await import("pdfjs-dist/legacy/build/pdf.mjs");
  const doc = await pdfjs.getDocument({
    data: new Uint8Array(buf),
    useSystemFonts: true,
  }).promise;

  const boxes: TextBox[] = [];
  for (let p = 1; p <= doc.numPages; p++) {
    const page = await doc.getPage(p);
    const content = await page.getTextContent();
    for (const item of content.items as any[]) {
      if (!item.str || !item.str.trim()) continue;
      const x = item.transform[4];
      const baseline = item.transform[5];
      boxes.push({
        page: p,
        text: item.str,
        x0: x,
        x1: x + item.width,
        y0: baseline,
        y1: baseline + item.height,
      });
    }
  }
  return boxes;
}

/**
 * No two text boxes on a page may share ink. Tolerance absorbs the sub-point
 * slop between pdfjs' reported glyph box and the real inked extent (descenders,
 * side bearings) — a real collision is many points deep, not fractions.
 */
function expectNoOverlappingText(boxes: TextBox[]): void {
  const TOL = 1.5;
  const byPage = new Map<number, TextBox[]>();
  for (const b of boxes) byPage.set(b.page, [...(byPage.get(b.page) ?? []), b]);

  for (const [page, items] of byPage) {
    for (let i = 0; i < items.length; i++) {
      for (let j = i + 1; j < items.length; j++) {
        const a = items[i]!;
        const b = items[j]!;
        const xOverlap = Math.min(a.x1, b.x1) - Math.max(a.x0, b.x0);
        const yOverlap = Math.min(a.y1, b.y1) - Math.max(a.y0, b.y0);
        expect(
          xOverlap > TOL && yOverlap > TOL,
          `page ${page}: ${JSON.stringify(a.text)} overlaps ${JSON.stringify(b.text)} ` +
            `by ${xOverlap.toFixed(1)}x${yOverlap.toFixed(1)}pt`
        ).toBe(false);
      }
    }
  }
}

/** Page text with footer/header chrome removed — what's left must be content. */
function stripChrome(pageText: string): string {
  return pageText
    .replace(/SecureLogic AI\s*[—–-]\s*Confidential/g, "")
    .replace(/Page \d+ of \d+/g, "")
    .replace(/CONFIDENTIAL/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function expectNoArtifactPages(parsed: ParsedPdf): void {
  for (const page of parsed.pages) {
    const content = stripChrome(page.text);
    expect(
      content.length,
      `page ${page.num} of ${parsed.total} is blank or footer-only: ${JSON.stringify(page.text)}`
    ).toBeGreaterThan(20);
  }
}

function expectConsistentPageNumbers(parsed: ParsedPdf): void {
  const labels = [...parsed.fullText.matchAll(/Page (\d+) of (\d+)/g)];
  // A footer on every page…
  expect(labels.length).toBe(parsed.total);
  // …each declaring the true total…
  for (const m of labels) {
    expect(Number(m[2])).toBe(parsed.total);
  }
  // …and covering every page number exactly once.
  const numbers = labels.map((m) => Number(m[1])).sort((a, b) => a - b);
  expect(numbers).toEqual(Array.from({ length: parsed.total }, (_, i) => i + 1));
}

